-- Enable Row Level Security (RLS) is enabled by default on new tables in Supabase, but we explicitly enable it.

-- 1. Site Settings Table
-- Stores all global content (Hero, Contact, About, Socials)
create table public.site_settings (
  key text not null primary key,
  value jsonb not null, -- Using JSONB for flexibility (strings, arrays, objects)
  label text, -- Human readable label for the admin UI
  type text check (type in ('text', 'textarea', 'image', 'json', 'array')) default 'text'
);

alter table public.site_settings enable row level security;

-- Policy: Allow read access to everyone (public content)
create policy "Allow public read access" on public.site_settings
  for select using (true);

-- Policy: Allow all access to authenticated users (Admin)
create policy "Allow admin full access" on public.site_settings
  for all using (auth.role() = 'authenticated');



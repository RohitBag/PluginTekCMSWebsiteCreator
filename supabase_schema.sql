-- 10. Profiles Table (Auth)
-- ==========================================
-- USER AUTHENTICATION & BOOKMARKS (Updated)
-- ==========================================

-- 1. Create Profiles Table
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade primary key,
  email text,
  full_name text,
  phone text,
  role text default 'user' check (role in ('admin', 'user')),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Enable RLS
alter table public.profiles enable row level security;

-- 2. Create Bookmarks Table
create table if not exists public.bookmarks (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete cascade not null,
  item_id bigint references public.items(id) on delete cascade not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  unique(user_id, item_id)
);

-- Enable RLS
alter table public.bookmarks enable row level security;

-- 3. Helper Functions

-- 3a. Profile Creation Trigger Function
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, email, full_name, phone, role)
  values (
    new.id, 
    new.email, 
    new.raw_user_meta_data->>'full_name',
    new.raw_user_meta_data->>'phone',
    'user' -- Defaults to 'user'
  );
  return new;
end;
$$ language plpgsql security definer;

-- 3b. Admin Check Function (Fixes Infinite Recursion)
-- Security Definer bypasses RLS on 'profiles' table to check role safely
create or replace function public.is_admin()
returns boolean as $$
begin
  return exists (
    select 1
    from public.profiles
    where id = auth.uid()
    and role = 'admin'
  );
end;
$$ language plpgsql security definer;

-- 4. Triggers

-- Trigger for new user creation
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- 5. RLS Policies for Profiles

-- Drop existing policies to prevent conflicts if re-running
drop policy if exists "Users can view own profile" on public.profiles;
drop policy if exists "Admins can view all profiles" on public.profiles;
drop policy if exists "Users can update own profile" on public.profiles;

-- Create Policies
create policy "Users can view own profile" on public.profiles
  for select using (auth.uid() = id);

-- Admin Policy using Secure Function
create policy "Admins can view all profiles" on public.profiles
  for select using (public.is_admin());

create policy "Users can update own profile" on public.profiles
  for update using (auth.uid() = id);

-- 6. RLS Policies for Bookmarks

-- Drop existing policies
drop policy if exists "Users can view own bookmarks" on public.bookmarks;
drop policy if exists "Users can create own bookmarks" on public.bookmarks;
drop policy if exists "Users can delete own bookmarks" on public.bookmarks;

-- Create Policies
create policy "Users can view own bookmarks" on public.bookmarks
  for select using (auth.uid() = user_id);

create policy "Users can create own bookmarks" on public.bookmarks
  for insert with check (auth.uid() = user_id);

create policy "Users can delete own bookmarks" on public.bookmarks
  for delete using (auth.uid() = user_id);

-- 7. Column-Level Security for Roles
revoke update on public.profiles from authenticated;
grant update (full_name, phone) on public.profiles to authenticated;

-- 8. Service Role Grants
grant all on public.profiles to service_role;
grant all on public.bookmarks to service_role;

